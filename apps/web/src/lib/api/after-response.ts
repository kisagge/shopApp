import { after } from 'next/server';

/**
 * 응답을 막지 않아도 되는 일을 응답 **뒤로** 미룬다.
 *
 * **왜 필요한가.** 결제 확정 창구가 1.3초를 썼는데, 그중 승인 뒤에 붙은
 * 일(매출 기록 · 안내 메일)이 응답 앞을 막고 있었다. 둘 다 실패해도 승인을
 * 되돌리지 않는 일이다 — 즉 사용자가 기다릴 이유가 없는 일이다. 이 배포는
 * DB 왕복 하나가 141ms 라(질의 내용과 무관하게 고정이었다) 왕복 한 번을
 * 응답 뒤로 미루는 것만으로 화면이 그만큼 빨리 바뀐다.
 *
 * **`void work()` 로 던져 두지 않는 이유.** 서버리스는 응답을 보내고 나면
 * 실행을 얼려 버린다. 붙잡아 두지 않으면 메일이 보내지다 만다. `after` 가
 * 그 붙잡아 두는 일을 한다.
 *
 * **요청 밖에서는 그 자리에서 돌린다.** `after` 는 요청 범위 밖에서 부르면
 * 던진다(조용히 버리지 않는다 — 확인했다). 단위 검사는 요청 없이 함수를
 * 직접 부르므로, 그때는 약속을 돌려주고 부르는 쪽이 기다리게 한다. 그래야
 * 검사가 **실제로 일어난 일**을 보게 된다. 미뤘다는 이유로 검사에서 사라지면
 * 그 일은 아무도 안 보는 일이 된다.
 */
export function afterResponse(work: () => Promise<void>): Promise<void> | void {
  try {
    after(work);
  } catch {
    return work();
  }
}
