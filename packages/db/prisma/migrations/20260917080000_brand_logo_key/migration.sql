-- 브랜드 로고 파일의 저장소 키.
--
-- 로고 주소(logoUrl)는 매장의 브랜드 화면이 그리는데, 그 값을 쓰는 곳이 없었다.
-- 올리는 길을 만들면서 키를 함께 둔다 — 주소만 두면 로고를 바꿀 때 옛 파일을 지울
-- 길이 없고, 주소에서 키를 거꾸로 뽑으면 저장소 주소 규칙이 바뀌는 날 엉뚱한 것을 지운다.
--
-- 덧붙이기만 한다. 시드는 로고를 비워 둔다. 이 칸이 생기기 전에 주소만 적힌 로고가 있다면
-- 키가 비어 있으므로, 바꿀 때 옛 파일은 지우지 않고 둔다(우리가 올린 것인지 알 수 없다).
ALTER TABLE "brands" ADD COLUMN "logoKey" TEXT;
