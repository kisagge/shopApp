/** 편집기가 만드는 나무와 같은 모양으로 담는다 — 운영진이 그대로 이어서 고칠 수 있어야 한다 */
const asRichText = (paragraphs: readonly string[]) => ({
  type: 'doc',
  content: paragraphs.map((text) => ({ type: 'paragraph', content: [{ type: 'text', text }] })),
});

export async function seedPolicies(): Promise<void> {
  const effectiveAt = new Date('2026-01-01T00:00:00+09:00');

  for (const policy of POLICIES) {
    await prisma.policy.upsert({
      where: { kind: policy.kind },
      // 운영진이 고친 문서를 시드가 되돌리지 않는다
      update: {},
      create: {
        kind: policy.kind,
        title: policy.title,
        body: policy.paragraphs.join('\n\n'),
        bodyRich: asRichText(policy.paragraphs),
        effectiveAt,
      },
    });
  }

  console.log(`  약관·방침 ${POLICIES.length}개`);
}
